#!/bin/bash
# assemble.sh <out>: the engine guest, built from THIS checkout's product guest (prover/methods/guest) and the shared
# sources it #[path]-includes (libzync, coinbase-smt), laid out in <out> with the same relative paths, plus the engine's
# edits (edits.py), its batch-signature module and manifest. The product tree is never modified. Then:
#   HZ_BASE=<base> SECP_DIR=<base>/secp256k1 hzengine build --dir <keys> --guest <out>/prover/methods/guest
# where <base> comes from base.sh.
set -euo pipefail
OUT=${1:?usage: assemble.sh <out>}
K=$(cd "$(dirname "$0")" && pwd); E=$(cd "$K/.." && pwd); R=$(cd "$E/.." && pwd)
G=$OUT/prover/methods/guest
rm -rf "$OUT/prover" "$OUT/libzync" "$OUT/coinbase-smt"
mkdir -p "$OUT/prover/methods" "$OUT/libzync" "$OUT/coinbase-smt"
cp -r "$R/prover/methods/guest" "$G"; rm -rf "$G/target" "$G/Cargo.lock" "$G/openvm-init.rs"
cp -r "$R/libzync/src" "$OUT/libzync/src"; cp -r "$R/coinbase-smt/src" "$OUT/coinbase-smt/src"
cp "$K/batch_ecdsa_ovm.rs" "$K/msm_ovm.rs" "$G/src/"
python3 "$K/edits.py" "$G/src/main.rs" "$OUT/libzync/src/coinlog.rs"
sed "s|@ENGINE@|$E|g" "$K/Cargo.toml.in" > "$G/Cargo.toml"
cp "$K/build.rs" "$G/build.rs"
# HZ_TEST_LINEAGE=<file>: the test variant's lineage (guest feature test-lineage: lineage/test.rs, never a published
# image) replaced in the ASSEMBLED copy, e.g. to pin an engine predecessor for a handover rehearsal. The checkout's
# lineage/test.rs is never modified.
if [ -n "${HZ_TEST_LINEAGE:-}" ]; then
    cp "$HZ_TEST_LINEAGE" "$G/src/lineage/test.rs.lineage"
    python3 - "$G/src/lineage/test.rs" "$G/src/lineage/test.rs.lineage" <<'PY'
import sys
p, new = sys.argv[1], open(sys.argv[2]).read().strip()
s = open(p).read(); a = "pub const LINEAGE: &[crate::handover_pin::Handover] = &[];"
assert s.count(a) == 1, "lineage/test.rs: the empty LINEAGE line moved"
open(p, "w").write(s.replace(a, new))
PY
    rm "$G/src/lineage/test.rs.lineage"
    echo "  test lineage: $(grep -c 'Handover {' "$G/src/lineage/test.rs") handover(s) pinned (assembled copy only)"
fi
# HZ_OVM_XVER_KEYS=<dir of predecessor key files, each named <its SHA-256>.vk> (engine/HANDOVER.md step 2): the keys an
# image with the `ovm-xver` feature carries, embedded (src/xver_keys/, listed in src/xver_keys.rs: the image id commits
# to their bytes), and every OpenVM / stark-backend crate from ONE patched tree (engine/scripts/openvm_src.sh: the
# pinned commits, nozstd for the verifier, nologging for stark-sdk), so the guest's runtime and its verifier are one copy.
if [ -n "${HZ_OVM_XVER_KEYS:-}" ]; then
    cp "$K/xver_ovm.rs" "$G/src/"
    mkdir -p "$G/src/xver_keys"
    {
        echo "// GENERATED by engine/guest/assemble.sh from HZ_OVM_XVER_KEYS: (pin = SHA-256 of the key file, the key file)"
        echo "// (pin, key file, OpenVM version: super::V2_1_0 for a key at the top of the dir, super::V2_0_2 under v2.0.2/)"
        echo "pub const KEYS: &[(&[u8; 32], &[u8], u8)] = &["
        for f in "$HZ_OVM_XVER_KEYS"/*.vk "$HZ_OVM_XVER_KEYS"/v2.0.2/*.vk; do
            [ -e "$f" ] || continue
            pin=$(sha256sum "$f" | cut -d' ' -f1)
            [ "$(basename "$f" .vk)" = "$pin" ] || { echo "$f: name it <its SHA-256>.vk (it hashes to $pin)" >&2; exit 1; }
            ver=V2_1_0; case "$f" in */v2.0.2/*) ver=V2_0_2 ;; esac
            cp "$f" "$G/src/xver_keys/"
            echo "    (&[$(echo "$pin" | sed 's/../0x&, /g; s/, $//')], include_bytes!(\"xver_keys/$pin.vk\"), super::$ver),"
        done
        echo "];"
    } > "$G/src/xver_keys.rs"
    OVM=$OUT/openvm-src
    (cd "$R" && engine/scripts/openvm_src.sh "$OVM" engine/wasm-verify/openvm-abi-stable.patch engine/handover/openvm-verify-nozstd.patch \
        engine/handover/stark-sdk-nologging.patch > /dev/null)
    { echo; echo '[patch."https://github.com/openvm-org/openvm.git"]'
      find "$OVM/openvm/crates" "$OVM/openvm/extensions" "$OVM/openvm/guest-libs" -name Cargo.toml -not -path "*/target/*" \
           -not -path "*/tests/*" -not -path "*/programs/*" -not -path "*/examples/*" -not -path "*/benches/*" -not -path "*/benchmarks/*" | LC_ALL=C sort |
      while read -r f; do n=$(sed -n '/^\[package\]/,/^\[/{s/^name = "\(.*\)"/\1/p}' "$f" | head -1); [ -n "$n" ] && echo "$n = { path = \"$(dirname "$f")\" }"; done
      echo; echo '[patch."https://github.com/openvm-org/stark-backend.git"]'
      find "$OVM/stark-backend/crates" -name Cargo.toml -not -path "*/target/*" -not -path "*/tests/*" -not -path "*/benches/*" | LC_ALL=C sort |
      while read -r f; do n=$(sed -n '/^\[package\]/,/^\[/{s/^name = "\(.*\)"/\1/p}' "$f" | head -1); [ -n "$n" ] && echo "$n = { path = \"$(dirname "$f")\" }"; done
    } >> "$G/Cargo.toml"
    # a v2.0.2 predecessor: its own verifier, from the pinned v2.0.2 tree (path dependencies, links renamed: a second
    # OpenVM in the graph), as hazync-engine-verify-v2-0-2 (engine/handover/v2.0.2/make_verify.sh)
    if ls "$HZ_OVM_XVER_KEYS"/v2.0.2/*.vk > /dev/null 2>&1; then
        V2=$OUT/openvm-src-v2.0.2; HV=$R/engine/handover/v2.0.2
        (cd "$R" && OVM_VERSION=v2.0.2 OVM_SBK_PATHS=1 engine/scripts/openvm_src.sh "$V2" engine/wasm-verify/openvm-abi-stable.patch \
            "$HV/openvm-v2.0.2-verify-nozstd.patch" "$HV/openvm-v2.0.2-links.patch" engine/handover/stark-sdk-nologging.patch \
            "$HV/stark-v2.0.1-links.patch" > /dev/null)
        "$HV/make_verify.sh" "$V2" "$OUT/verify-v2.0.2" > /dev/null
        python3 - "$G/Cargo.toml" "$OUT/verify-v2.0.2" <<'PY'
import sys
p, v = sys.argv[1], sys.argv[2]; s = open(p).read()
a = 'ovm-xver = ["dep:hazync-engine-verify"]\n'
assert s.count(a) == 1
s = s.replace(a, a + 'ovm-xver-v2_0_2 = ["ovm-xver", "dep:hazync-engine-verify-v2-0-2"]\n')
a = "[dependencies]\n"
s = s.replace(a, a + f'hazync-engine-verify-v2-0-2 = {{ path = "{v}", optional = true }}\n', 1)
open(p, "w").write(s)
PY
        echo "  ovm-xver: OpenVM v2.0.2's verifier added (feature ovm-xver-v2_0_2)"
    fi
    echo "  ovm-xver: $(grep -c include_bytes "$G/src/xver_keys.rs") predecessor key(s) embedded; OpenVM from $OVM (patched)"
fi
# The pinned lock (reproduce/engine-locks, engine/ROADMAP.md 4.1): without it every build re-resolves crates.io and an
# id can move with a crate release. HZ_UNPINNED_LOCK=1 leaves it out (a manifest change that needs a new lock: make it,
# check the id, and pin it there).
if [ -z "${HZ_OVM_XVER_KEYS:-}" ] && [ "${HZ_UNPINNED_LOCK:-0}" != 1 ]; then
    cp "$R/reproduce/engine-locks/core.Cargo.lock" "$G/Cargo.lock"; echo "  lock: reproduce/engine-locks/core.Cargo.lock (pinned)"
fi   # (an ovm-xver build has its own manifest: no pinned lock for it)
echo "assembled $G (product $(git -C "$R" rev-parse --short HEAD))"
