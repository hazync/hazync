//! Review R3-1 #1 (28.11.2026): OpenVM's add_ne, double and div leave their result UNCONSTRAINED in degenerate cases
//! (add_ne on equal x, double on the identity / (0,0) encoding, 0/0). msm_ovm.rs never reaches them: equal x is tested
//! before add_ne, doubling only ever acts on a non-identity point, identity bases are dropped first. These tests check
//! the MSM against an INDEPENDENT implementation (RustCrypto's k256, no shared code with OpenVM's curve arithmetic) on
//! inputs built to hit every one of those guarded branches (repeated keys, repeated R, R = ±Q, equal-x pairs, scalars
//! 0 / 1 / n-1, identity bases, Straus and Pippenger sizes), and PROVE the branches were reached: the instrumented copy
//! made by build.rs counts each one, and every counter must be non-zero.
extern crate std;
use alloc::vec::Vec;
use k256::{Secp256k1Coord as Fq, Secp256k1Point as P, Secp256k1Scalar as Fr};
use openvm_algebra_guest::{IntMod, Reduce};
use openvm_ecc_guest::weierstrass::WeierstrassPoint;
use rc_k256::elliptic_curve::group::{prime::PrimeCurveAffine, Group};
use rc_k256::elliptic_curve::sec1::{FromEncodedPoint, ToEncodedPoint};
use rc_k256::elliptic_curve::PrimeField;
use rc_k256::{AffinePoint, EncodedPoint, ProjectivePoint, Scalar};

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u64 { self.0 ^= self.0 << 13; self.0 ^= self.0 >> 7; self.0 ^= self.0 << 17; self.0 }
    fn bytes(&mut self, n: usize) -> [u8; 32] {
        let mut b = [0u8; 32];
        for k in 0..n { b[k] = self.next() as u8; }
        b
    }
}

fn id() -> P { <P as WeierstrassPoint>::IDENTITY }

/// OpenVM point -> RustCrypto point (big-endian SEC1 coordinates).
fn to_rc(p: &P) -> ProjectivePoint {
    if *p == id() { return ProjectivePoint::IDENTITY; }
    let (mut x, mut y) = ([0u8; 32], [0u8; 32]);
    x.copy_from_slice(p.x().as_le_bytes()); x.reverse();
    y.copy_from_slice(p.y().as_le_bytes()); y.reverse();
    let ep = EncodedPoint::from_affine_coordinates(&x.into(), &y.into(), false);
    ProjectivePoint::from(Option::<AffinePoint>::from(AffinePoint::from_encoded_point(&ep)).expect("a curve point"))
}

/// RustCrypto point -> OpenVM point, through OpenVM's own on-curve check.
fn from_rc(q: &ProjectivePoint) -> P {
    if bool::from(q.is_identity()) { return id(); }
    let a = q.to_affine();
    assert!(!bool::from(a.is_identity()));
    let ep = a.to_encoded_point(false);
    let x = Fq::from_be_bytes(ep.x().unwrap()).expect("x < p");
    let y = Fq::from_be_bytes(ep.y().unwrap()).expect("y < p");
    // SAFETY: off-zkvm software arithmetic; from_xy checks the curve equation
    unsafe { P::from_xy(x, y) }.expect("on the curve")
}

/// OpenVM scalar (reduced) -> RustCrypto scalar.
fn sc_rc(s: &Fr) -> Scalar {
    let mut b = [0u8; 32];
    b.copy_from_slice(s.as_le_bytes()); b.reverse();
    Option::<Scalar>::from(Scalar::from_repr(b.into())).expect("a reduced scalar")
}

fn rc_msm(s: &[Fr], p: &[P]) -> ProjectivePoint {
    s.iter().zip(p).fold(ProjectivePoint::IDENTITY, |acc, (k, q)| acc + to_rc(q) * sc_rc(k))
}

/// Both copies of the MSM (the guest's source and the counting copy) must equal the independent sum.
fn check(s: &[Fr], p: &[P], what: &str) -> P {
    let want = rc_msm(s, p);
    let got = crate::msm::msm(s, p);
    assert!(to_rc(&got) == want, "{what}: msm_ovm differs from RustCrypto's k256 (n = {})", s.len());
    let got_cov = crate::msm_cov::msm(s, p);
    assert!(got_cov == got, "{what}: the counting copy differs from the guest's source (n = {})", s.len());
    got
}

fn fr_rand(r: &mut Rng, n: usize) -> Fr { Fr::reduce_le_bytes(&r.bytes(n)) }

#[test]
fn against_rustcrypto_with_every_guarded_branch() {
    let mut r = Rng(0x243f6a8885a308d3);
    let g = <P as openvm_ecc_guest::CyclicGroup>::GENERATOR;
    let n_minus_1 = &Fr::ZERO - &Fr::ONE;
    let two = &Fr::ONE + &Fr::ONE;
    // a few keys (so repeats and equal-x pairs are frequent), generated by RustCrypto and brought over
    let keys: Vec<P> = (0..3).map(|_| from_rc(&(ProjectivePoint::GENERATOR * sc_rc(&fr_rand(&mut r, 32))))).collect();
    assert!(to_rc(&g) == ProjectivePoint::GENERATOR, "generator mapping");
    let special = [Fr::ZERO, Fr::ONE, n_minus_1.clone(), two.clone()];
    let mut cases = 0usize;

    // 1. small and medium sizes (Straus n <= 4, Pippenger above), points from {keys, -keys, G, identity}, scalars mixed
    for &n in &[0usize, 1, 2, 3, 4, 5, 6, 8, 12, 33, 200] {
        for t in 0..60 {
            let mut s = Vec::new();
            let mut p = Vec::new();
            for i in 0..n {
                let v = r.next();
                s.push(match v % 6 { 0..=2 => special[(v / 6 % 4) as usize].clone(), 3 => fr_rand(&mut r, 16), _ => fr_rand(&mut r, 32) });
                let q = if v % 7 == 0 { g.clone() } else { keys[(r.next() % 3) as usize].clone() };
                p.push(match r.next() % 5 { 0 => -&q, 1 => id(), _ => q });
                // force equal-x pairs into one bucket: the same point twice, and a point with its negation, same scalar
                if i > 0 && t % 4 == 1 { p[i] = p[i - 1].clone(); s[i] = s[i - 1].clone(); }
                if i > 0 && t % 4 == 2 { p[i] = -&p[i - 1]; s[i] = s[i - 1].clone(); }
            }
            check(&s, &p, "mixed");
            cases += 1;
        }
    }

    // 2. the batch equation's shape on honest tuples (R = u1·G + u2·Q): Σ z·u2·Q − Σ z·R + (Σ z·u1)·G = O, with
    //    repeated keys, repeated R, and R = ±Q (u1 = 0, u2 = ±1); then one forged tuple must give a NON-identity sum
    for &m in &[1usize, 2, 5, 40, 300] {
        let (mut s, mut p) = (Vec::new(), Vec::new());
        let mut zu1 = Fr::ZERO;
        for j in 0..m {
            let q = keys[j % 3].clone();
            let (u1, u2) = match j % 5 {
                0 => (Fr::ZERO, Fr::ONE),          // R = Q
                1 => (Fr::ZERO, n_minus_1.clone()), // R = -Q
                2 => (fr_rand(&mut r, 32), fr_rand(&mut r, 32)),
                _ => (Fr::ONE, Fr::ONE),           // the same R for every tuple of this key (repeated R)
            };
            let rpt = from_rc(&(ProjectivePoint::GENERATOR * sc_rc(&u1) + to_rc(&q) * sc_rc(&u2)));
            let z = fr_rand(&mut r, 16);
            s.push(&z * &u2); p.push(q.clone());
            s.push(&Fr::ZERO - &z); p.push(rpt);
            zu1 = &zu1 + &(&z * &u1);
        }
        s.push(zu1); p.push(g.clone());
        let out = check(&s, &p, "honest batch");
        assert!(out == id(), "honest batch (m = {m}) must sum to the identity");
        // forge: move one R by G; the weighted sum is then z·G != O
        let k = p.len() - 2;
        let moved = from_rc(&(to_rc(&p[k]) + ProjectivePoint::GENERATOR));
        let mut pf = p.clone(); pf[k] = moved;
        let bad = check(&s, &pf, "forged batch");
        assert!(bad != id(), "forged batch (m = {m}) must not sum to the identity");
        cases += 2;
    }

    // 3. exact cancellation and all-zero scalars at Pippenger size (k·P + (n-k)·P = O; every scalar 0)
    for _ in 0..20 {
        let k = fr_rand(&mut r, 32);
        let mut s: Vec<Fr> = (0..6).map(|_| fr_rand(&mut r, 32)).collect();
        let mut p: Vec<P> = (0..6).map(|i| keys[i % 3].clone()).collect();
        s.push(k.clone()); p.push(keys[0].clone());
        s.push(&Fr::ZERO - &k); p.push(keys[0].clone());
        check(&s, &p, "cancel");
        let zeros: Vec<Fr> = (0..7).map(|_| Fr::ZERO).collect();
        assert!(check(&zeros, &p[..7], "all zero") == id());
        cases += 2;
    }

    // every guarded branch was reached (crate::cov; numbering in build.rs)
    let counts = crate::cov::counts();
    std::println!("R3-1 #1: {cases} cases against RustCrypto's k256; branch counts {:?}", &counts[1..]);
    for (k, &c) in counts.iter().enumerate().skip(1) {
        assert!(c > 0, "branch {k} of msm_ovm.rs was never reached (build.rs lists them)");
    }
}
