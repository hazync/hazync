#!/bin/bash
# assemble_guest.sh <zyncAPP> <out dir>: a zyncAPP guest (prover/zyncapps/methods/<zyncAPP>: hints, utreexo, utreexo-tip,
# zeroconf) for the engine (FEASIBILITY Q20). The zAPP's OWN source, copied, and the libzync files it #[path]-includes,
# copied beside it (lz_<file>.rs) with the core guest's coin log edit (engine/guest/coinlog_ovm.py). The only edits to
# its main.rs (each anchored, exactly once):
#   1) no `#![no_main]` / `risc0_zkvm::guest::entry!(main)`: an OpenVM std guest is an ordinary `fn main`;
#   2) `fn main` becomes `hz_main`, and a new `main` calls it, then `env::finalize()` (the journal's sha256 becomes the
#      proof's public values on every path out, an early `return` included);
#   3) each libzync #[path] points at its copy.
# Dependencies: the engine platform (`risc0_zkvm` on OpenVM), serde, and sha2: the engine's (OpenVM's SHA-256
# extension) where only SHA-256 is used, RustCrypto's (software) for the utreexo guests (Floresta's leaf is SHA-512/256).
set -euo pipefail
Z=${1:?zyncAPP}; OUT=$(readlink -m "${2:?out dir}")
HERE=$(cd "$(dirname "$0")" && pwd); ENGINE=$(cd "$HERE/.." && pwd); REPO=$(cd "$ENGINE/.." && pwd)
SRC=$REPO/prover/zyncapps/methods/$Z
[ -f "$SRC/src/main.rs" ] || { echo "no guest $SRC"; exit 1; }
rm -rf "$OUT"; mkdir -p "$OUT/src"
cp "$SRC"/src/*.rs "$OUT/src/"
python3 - "$OUT/src/main.rs" "$REPO" "$OUT/src" <<'PY'
import re, shutil, sys, os
p, repo, out = sys.argv[1], sys.argv[2], sys.argv[3]
s = open(p).read()
def rep(old, new):
    global s
    assert s.count(old) == 1, ("anchor not unique / missing", old[:60], s.count(old))
    s = s.replace(old, new)
rep("#![no_main]\n", "")
rep("risc0_zkvm::guest::entry!(main);\n", "")
rep("\nfn main() {", "\nfn main() {   // ENGINE: the zAPP's main, then its journal's sha256 as the public values\n    hz_main();\n    risc0_zkvm::guest::env::finalize();\n}\n\nfn hz_main() {")
for m in re.findall(r'#\[path = "(\.\./\.\./\.\./\.\./\.\./libzync/src/([a-z_]+)\.rs)"\]', s):
    rel, name = m
    shutil.copy(os.path.join(repo, "libzync/src", name + ".rs"), os.path.join(out, "lz_" + name + ".rs"))
    rep('#[path = "%s"]' % rel, '#[path = "lz_%s.rs"]' % name)
# the core guest's files a zAPP include!s (handover_pin.rs: the lineage format), copied beside it as they are
for rel, name in re.findall(r'include!\("(\.\./\.\./\.\./\.\./methods/guest/src/([a-z_]+)\.rs)"\)', s):
    shutil.copy(os.path.join(repo, "prover/methods/guest/src", name + ".rs"), os.path.join(out, "core_" + name + ".rs"))
    rep('include!("%s")' % rel, 'include!("core_%s.rs")' % name)
assert "../libzync" not in s and "../methods/" not in s, "an include outside the copied files remains"
open(p, "w").write(s)
print("edits applied:", p)
PY
[ -f "$OUT/src/lz_coinlog.rs" ] && python3 "$ENGINE/guest/coinlog_ovm.py" "$OUT/src/lz_coinlog.rs"
EXTRA=$(sed -n '/^\[dependencies\]/,/^\[/p' "$SRC/Cargo.toml" | grep -v '^\[' | grep -v '^risc0-zkvm\|^sha2\|^serde\|^#\|^$' || true)
case $Z in
  utreexo|utreexo-tip) SHA='sha2 = { version = "0.10", default-features = false, features = ["compress"] }';;
  *) SHA="sha2 = { path = \"$ENGINE/platform/sha2\", package = \"hazync-engine-sha2\", features = [\"compress\"] }";;
esac
cat > "$OUT/Cargo.toml" <<EOF
# GENERATED by engine/zapps/assemble_guest.sh: the $Z zyncAPP guest on the engine (source: prover/zyncapps/methods/$Z).
[package]
name = "zyncapp-$Z-engine"
version = "0.1.0"
edition = "2021"

[workspace]

[profile.release]
lto = "fat"
codegen-units = 1

[dependencies]
risc0-zkvm = { path = "$ENGINE/platform/risc0-zkvm", package = "hazync-engine-platform" }
$SHA
serde = { version = "1", default-features = false, features = ["derive", "alloc"] }
openvm = { git = "https://github.com/openvm-org/openvm.git", tag = "v2.1.0", features = ["std"] }
$EXTRA
EOF
echo "assembled $OUT ($Z)"
